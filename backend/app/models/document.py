"""
==============================================================================
FILE: backend/app/models/document.py
PURPOSE: Defines database tables for Document storage, AI-extracted Notice
         metadata, and Academic Resources (Syllabi & Question Papers).
==============================================================================
ARCHITECTURAL DECISION:
Why not store the raw PDF files directly inside PostgreSQL (as BLOBs)?
- Storing large binary PDFs inside SQL tables slows down queries, causes database
  bloat, and makes backups very heavy.
- Best Practice: Store the actual PDF on the filesystem (or cloud S3 storage),
  and store the metadata (title, file path, upload date, extracted criteria)
  inside PostgreSQL!
==============================================================================
"""

from datetime import datetime
from sqlalchemy import Column, Integer, String, Boolean, Float, ForeignKey, DateTime, Text, JSON
from sqlalchemy.orm import relationship

from app.database import Base


class Document(Base):
    """
    The parent Document table.
    Every uploaded file (notice, circular, syllabus, previous-year paper) gets a row here.
    """
    __tablename__ = "documents"

    id = Column(Integer, primary_key=True, index=True)

    # Human-readable title (e.g. "TCS Campus Placement Drive 2026")
    title = Column(String, nullable=False)

    # Original uploaded filename (e.g. "TCS_Circular_Final.pdf")
    file_name = Column(String, nullable=False)

    # Safe filesystem path where the PDF is stored (e.g. "uploads/notices/1709...pdf")
    file_path = Column(String, nullable=False)

    # Size of the PDF file in bytes
    file_size_bytes = Column(Integer, default=0)

    # Category: "notice", "syllabus", "question_paper", "circular", "rule"
    category = Column(String, index=True, nullable=False)

    # Flag: True once the document has been processed by PyPDF and indexed in RAG
    is_processed = Column(Boolean, default=False)

    # Foreign Key: ID of the faculty/admin user who uploaded the document
    uploaded_by_id = Column(Integer, ForeignKey("users.id"), nullable=True)

    # Timestamp when the file was uploaded
    created_at = Column(DateTime, default=datetime.utcnow)

    # =========================================================================
    # Relationships
    # =========================================================================
    
    # Links to the User who uploaded this file
    uploader = relationship("User", back_populates="uploaded_documents")

    # 1-to-1 link to extracted notice details (if category is "notice")
    notice_metadata = relationship(
        "NoticeMetadata",
        back_populates="document",
        uselist=False,
        cascade="all, delete-orphan"
    )

    # 1-to-1 link to academic catalog details (if category is "syllabus" or "question_paper")
    academic_resource = relationship(
        "AcademicResource",
        back_populates="document",
        uselist=False,
        cascade="all, delete-orphan"
    )

    # 1-to-Many link to notifications generated by this document
    notifications = relationship("Notification", back_populates="document", cascade="all, delete-orphan")


class NoticeMetadata(Base):
    """
    Notice-specific structured metadata extracted by Google Gemini AI.
    Used by the Eligibility Engine to match notices to students.
    """
    __tablename__ = "notice_metadata"

    id = Column(Integer, primary_key=True, index=True)

    # Foreign Key linking this metadata to the parent Document row
    document_id = Column(Integer, ForeignKey("documents.id", ondelete="CASCADE"), unique=True, nullable=False)

    # Clean title identified by Gemini
    title = Column(String, nullable=False)

    # AI-generated 2-3 sentence executive summary
    summary = Column(Text, nullable=True)

    # Specific action the student must take (e.g. "Register on portal before Oct 25")
    action_required = Column(Text, nullable=True)

    # Final submission deadline (e.g. "2026-10-25")
    deadline = Column(String, nullable=True)

    # Eligible branches: e.g. ["CSE", "IT"] or ["ALL"]
    eligible_branches = Column(JSON, default=list)

    # Eligible years: e.g. [3, 4] or [1, 2, 3, 4]
    eligible_years = Column(JSON, default=list)

    # Minimum CGPA cut-off: e.g. 7.5 (0.0 if no requirement)
    min_cgpa = Column(Float, default=0.0)

    # Contact email, phone, or office mentioned in the document
    contact_info = Column(String, nullable=True)

    # True if the deadline is within 3 days or marked urgent/mandatory
    is_urgent = Column(Boolean, default=False)

    # Relationship back to the parent Document
    document = relationship("Document", back_populates="notice_metadata")


class AcademicResource(Base):
    """
    Cataloging metadata for Syllabus and Previous-Year Question Papers.
    Enables structured student browsing: Branch -> Year -> Semester -> Subject.
    """
    __tablename__ = "academic_resources"

    id = Column(Integer, primary_key=True, index=True)

    # Foreign Key linking to the parent Document row
    document_id = Column(Integer, ForeignKey("documents.id", ondelete="CASCADE"), unique=True, nullable=False)

    # Engineering Branch: "CSE", "IT", "ECE", "ME", etc.
    branch = Column(String, index=True, nullable=False)

    # Academic Year: 1, 2, 3, 4
    year = Column(Integer, index=True, nullable=False)

    # Semester: 1 to 8
    semester = Column(Integer, index=True, nullable=False)

    # Subject Name (e.g., "Operating Systems", "Data Structures")
    subject_name = Column(String, index=True, nullable=False)

    # Official Course Code (e.g., "CS-501")
    subject_code = Column(String, index=True, nullable=True)

    # Resource Type: "syllabus", "question_paper", "notes"
    resource_type = Column(String, index=True, nullable=False)

    # Year of Examination (e.g., 2024 for a 2024 Question Paper)
    exam_year = Column(Integer, nullable=True)

    # Relationship back to the parent Document
    document = relationship("Document", back_populates="academic_resource")
